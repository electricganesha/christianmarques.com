async function run() {
  console.log(`Uploading ${CERTIFICATIONS_DATA.length} certifications to Firestore collection "certifications"...`);
  const batch = db.batch();
  for (const item of CERTIFICATIONS_DATA) {
    const ref = db.collection("certifications").doc(item.id);
    batch.set(ref, item, { merge: true });
  }
  await batch.commit();
  console.log("Upload completed successfully!");

  // Verification read
  const snapshot = await db.collection("certifications").orderBy("order", "asc").get();
  console.log(`Verified ${snapshot.size} docs in "certifications" collection:`);
  snapshot.docs.forEach((doc) => {
    const d = doc.data();
    console.log(` - [${d.order}] ${d.title} (${d.issuer}, ${d.issueDate || "Training"})`);
  });
}

run().catch((err) => {
  console.error("Upload failed:", err);
  process.exit(1);
});
